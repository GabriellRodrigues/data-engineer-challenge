import argparse
import sys
from pathlib import Path

from etl_jobs.gold.tables import GOLD_TABLES
from etl_jobs.silver.tables import SILVER_TABLES
from src.common.layer_build import LayerTable
from src.data_contract.contract_file_validator import load_contract
from src.lineage.graph import Lineage, Node, is_critical, references, to_mermaid
from src.utils.logger import get_logger
from src.utils.paths import (
    BRONZE_CONTRACTS_DIR,
    GOLD_CONTRACTS_DIR,
    GOLD_SQL_DIR,
    PROJECT_ROOT,
    SILVER_CONTRACTS_DIR,
    SILVER_SQL_DIR,
)

logger = get_logger("observability.lineage")

LAYERS = ["bronze", "silver", "gold"]
LINEAGE_DOC = PROJECT_ROOT / "docs" / "pipeline_docs" / "lineage.md"

DERIVED_LAYERS = (
    ("silver", SILVER_TABLES, SILVER_SQL_DIR, SILVER_CONTRACTS_DIR, "bronze"),
    ("gold", GOLD_TABLES, GOLD_SQL_DIR, GOLD_CONTRACTS_DIR, "silver"),
)

DOC_HEADER = """# Lineage

Generated by `make lineage` (`etl_jobs/observability/lineage.py`); do not edit by hand.
`test_lineage.py` fails when this file is out of date.

- **Dependencies** come from the SQL of each Silver and Gold table: a reference to `bronze_<table>` or
  `silver_<table>` is a dependency on the previous layer, a reference to another table of the same
  layer is a dependency inside the layer. Bronze tables are the datasets of the Bronze contracts.
- **Critical** tables are declared in their contract (`customProperties: [{property: critical,
  value: true}]`): they feed a P0 KPI directly. Tables upstream of a critical table are derived.
- `python -m etl_jobs.observability.lineage --impact silver.settlements` lists what a failure of a
  table affects.

Legend: red = critical, yellow = feeds a critical table, dashed = temporary step (not published).
"""


def _contract_critical(name: str, contracts_dir: Path) -> bool:
    return is_critical(load_contract(name, contracts_dir))


def build_lineage() -> Lineage:
    lineage = Lineage()
    names = {"bronze": sorted(p.stem for p in BRONZE_CONTRACTS_DIR.glob("*.yml"))}
    for name in names["bronze"]:
        lineage.add(Node("bronze", name, _contract_critical(name, BRONZE_CONTRACTS_DIR)))

    for layer, tables, sql_dir, contracts_dir, input_layer in DERIVED_LAYERS:
        names[layer] = [t.name for t in tables if t.publish]
        for table in tables:
            critical = table.publish and _contract_critical(table.name, contracts_dir)
            lineage.add(Node(layer, table.name, critical, table.publish))

        layer_names = [t.name for t in tables]
        for table in tables:
            _link_table(lineage, layer, table, sql_dir, input_layer, names[input_layer], layer_names)
    return lineage


def _link_table(
    lineage: Lineage,
    layer: str,
    table: LayerTable,
    sql_dir: Path,
    input_layer: str,
    input_names: list[str],
    layer_names: list[str],
) -> None:
    sql = table.sql(sql_dir)
    target = f"{layer}.{table.name}"
    for name in references(sql, input_names, prefix=f"{input_layer}_"):
        lineage.link(f"{input_layer}.{name}", target)
    for name in references(sql, layer_names) - {table.name}:
        lineage.link(f"{layer}.{name}", target)


def render(lineage: Lineage) -> str:
    rows = ["| Critical table | Upstream tables |", "|---|---|"]
    rows += [f"| `{node}` | {len(lineage.upstream(node))} |" for node in lineage.critical()]
    return "\n".join([
        DOC_HEADER,
        "```mermaid",
        to_mermaid(lineage, LAYERS),
        "```",
        "",
        "\n".join(rows),
        "",
    ])


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build the table lineage graph from the SQL and the contracts")
    parser.add_argument("--output", type=Path, default=LINEAGE_DOC, help="Markdown file to write")
    parser.add_argument("--impact", metavar="LAYER.TABLE", help="Only list the tables affected by this one")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None):
    args = parse_args(argv)
    lineage = build_lineage()

    if args.impact:
        if args.impact not in lineage.nodes:
            logger.error("Unknown table '%s'; use layer.table, e.g. silver.settlements", args.impact)
            sys.exit(1)
        affected = sorted(lineage.downstream(args.impact))
        logger.info("%s affects %d tables: %s", args.impact, len(affected), ", ".join(affected) or "none")
        logger.info("Critical tables affected: %s", ", ".join(lineage.impact(args.impact)) or "none")
        return

    args.output.write_text(render(lineage), encoding="utf-8")
    logger.info(
        "Lineage written to %s (%d tables, %d dependencies, %d critical)",
        args.output,
        len(lineage.nodes),
        len(lineage.edges),
        len(lineage.critical()),
    )


if __name__ == "__main__":
    main()
